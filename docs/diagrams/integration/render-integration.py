def sequence():
    mermaid = ["sequenceDiagram"]
    delivery = "RabbitMQ transport. At-least-once delivery. Deduplication by id."
    c = Canvas(1440, 1810, "Signal processing through RabbitMQ",
               "Outbox publication, publisher confirmation, Trade Maneuver intake, "
               "decline or broker execution, and result delivery. Manual mode requires human approval.")
    c.header("TRADE MANEUVER / MESSAGE FLOW", "Signal delivery and execution",
             delivery)

    for start, end, label in [(40, 510, "01 / PROXIMTYPE"), (530, 1220, "02 / TRADE MANEUVER"),
                               (1240, 1400, "03 / EXTERNAL")]:
        c.rule(start, 154, end, INK, 2)
        c.text(start, 178, label, 12, MUTED, mono=True)
    lanes = [
        ("PX", 150, "Application", "Proximtype"),
        ("PDB", 390, "PostgreSQL", "Proximtype"),
        ("MQ", 640, "RabbitMQ", "Trade Maneuver"),
        ("TM", 870, "TM application", "Trade Maneuver"),
        ("TDB", 1110, "TM PostgreSQL", "Trade Maneuver"),
        ("BR", 1320, "Broker", None),
    ]
    participants = {x: identity for identity, x, _, _ in lanes}
    for group in ["Proximtype", "Trade Maneuver", None]:
        if group:
            mermaid.append(f"    box {group}")
        for identity, _, label, owner in lanes:
            if owner == group:
                indent = "        " if group else "    "
                mermaid.append(f"{indent}participant {identity} as {mermaid_text(label)}")
        if group:
            mermaid.append("    end")
    for _, x, label, _ in lanes:
        c.text(x, 216, label, 18, weight=600, anchor="middle")
        c.path(f"M{x} 240 V1744", RULE, width=1, arrow=None, dash=True)

    def note(left, right, text):
        label = text if isinstance(text, str) else "\n".join(text)
        mermaid.append(f"    Note over {left},{right}: {mermaid_text(label)}")
        return text

    note("PX", "BR", delivery)

    # Alternative branches are outlined, without semantic background colours.
    c.rect(56, 936, 1328, 114, "none", RULE)
    c.rect(56, 1068, 1328, 482, "none", INK)

    def phase(y, number, title):
        mermaid.append(f"    %% {number} / {title}")
        c.rule(40, y - 30, 1400)
        c.rect(40, y - 14, 680, 26)
        c.text(40, y + 4, number, 25, ACCENT, mono=True)
        c.text(100, y + 1, title, 19, weight=600)

    def message(x1, x2, y, label, color=INK, arrow="ink", dash=False):
        operator = "-->>" if dash else "->>"
        mermaid.append(f"    {participants[x1]}{operator}{participants[x2]}: {mermaid_text(label)}")
        c.text((x1 + x2) / 2, y - 12, label, 15, color, anchor="middle")
        c.path(f"M{x1} {y} H{x2}", color, arrow=arrow, dash=dash)

    def self_message(x, y, label):
        mermaid.append(f"    {participants[x]}->>{participants[x]}: {mermaid_text(label)}")
        c.text(x + 14, y - 12, label, 15, MUTED)
        c.path(f"M{x} {y} H{x + 52} V{y + 24} H{x}", MUTED, arrow="muted")

    phase(300, "01", "Producer publication")
    message(150, 390, 354, "Data + outbox (atomic)")
    self_message(150, 410, "Translate to the v1 contract")
    message(150, 640, 478, "publish tm.trade-signal.v1", ACCENT, "accent")
    message(640, 150, 534, "publisher confirm → outbox: sent", MUTED, "muted", True)

    phase(612, "02", "Signal intake and validation")
    message(640, 870, 666, "Deliver signal")
    message(870, 1110, 724, "Check id in inbox")
    c.rect(766, 742, 434, 34, SURFACE)
    c.text(983, 764, note("TM", "TDB", "Duplicate: ack and stop processing"), 13, MUTED, anchor="middle", mono=True)
    self_message(870, 814, "Freshness, limits, session, kill switch")

    phase(918, "03", "Alternative paths: decline or approve")
    decline = "decline"
    mermaid.append(f"    alt {decline}")
    c.text(76, 963, decline.upper(), 12, MUTED, mono=True)
    message(870, 1110, 986, "inbox + SignalDeclined")
    message(870, 640, 1032, "SignalDeclined")
    approve = "approve"
    mermaid.append(f"    else {approve}")
    c.text(76, 1095, approve.upper(), 12, mono=True)
    c.rect(716, 1110, 652, 40, INK)
    mermaid.append("    opt Manual mode")
    c.text(1042, 1135, note("TM", "BR", "Manual mode / human approval required"), 14, PAPER, anchor="middle", mono=True)
    mermaid.append("    end")
    message(870, 1110, 1202, "inbox + Order (Approved)")
    message(870, 1320, 1262, "Submit order with clientOrderId")
    c.rect(716, 1284, 652, 64)
    c.path("M716 1284 V1348", ACCENT, width=2, arrow=None)
    mermaid.append("    opt Timeout")
    c.text(738, 1308, note("TM", "BR", ["On timeout: query order status with the broker.", "Do not submit the order again."]), 15, MUTED, gap=22)
    mermaid.append("    end")
    message(1320, 870, 1400, "Confirmation / execution", MUTED, "muted", True)
    message(870, 1110, 1460, "Persist Order state")
    message(870, 640, 1520, "OrderFilled")
    mermaid.append("    end")

    phase(1618, "04", "Acknowledgement and result delivery")
    message(870, 640, 1672, "ack after commit", MUTED, "muted", True)
    message(640, 150, 1728, "tm.trade-results → producer queue", dash=True)
    c.rule(40, 1758, 1400)
    c.text(40, 1784, note("PX", "BR", "Decline and approval are alternative paths. Results retain the signal identifier."), 14, MUTED)
    c.save("integration-sequence.svg")
    save_mermaid("integration-sequence.mmd", mermaid)


