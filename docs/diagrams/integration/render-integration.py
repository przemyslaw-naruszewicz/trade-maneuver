"""Generate SVG and Mermaid integration diagrams from shared content.

Run from the repository root: make diagrams
The SVG files use native text and geometry, without web fonts or embedded HTML.
Edit this script; both .svg and .mmd files are generated outputs.
"""

from html import escape
from pathlib import Path


ROOT = Path(__file__).resolve().parent
INK = "#181818"
MUTED = "#626262"
RULE = "#c9c9c5"
ACCENT = "#b83c25"
PAPER = "#ffffff"
SURFACE = "#f5f5f2"
SANS = "Arial, Helvetica, Liberation Sans, sans-serif"
MONO = "Consolas, Liberation Mono, DejaVu Sans Mono, monospace"
MERMAID_HEADER = "%% Generated by render-integration.py; edit that script and run make diagrams."


def mermaid_text(value):
    return escape(value, quote=True).replace("\n", "<br/>")


def save_mermaid(name, lines):
    (ROOT / name).write_text("\n".join([MERMAID_HEADER, *lines]) + "\n", encoding="utf-8")


class Flowchart:
    """Record the content used to draw the SVG and export its Mermaid equivalent."""

    def __init__(self, canvas):
        self.canvas = canvas
        self.nodes = {}
        self.edges = []
        self.groups = {
            "PX": "Proximtype / producer",
            "TM": "Trade Maneuver (TM)",
            "BR": "Trading broker / execution provider",
        }

    def node(self, identity, title, detail=None, *, kind="card", group=None):
        if identity in self.nodes:
            raise ValueError(f"Duplicate diagram node: {identity}")
        self.nodes[identity] = (title, detail, kind, group)
        return title, detail

    def note(self, identity, lines, *, group=None):
        text = lines if isinstance(lines, str) else "\n".join(lines)
        self.node(identity, text, kind="note", group=group)
        return lines

    def connect(self, source, target, path, *, label=None, **style):
        self.canvas.path(path, **style)
        operator = "-->"
        if style.get("arrow", "ink") is None:
            operator = "---"
        elif style.get("dash"):
            operator = "-.->"
        elif style.get("width", 1.6) >= 3:
            operator = "==>"
        self.edges.append((source, target, operator, label))
        return label

    def save(self, name):
        shapes = {
            "card": ('["', '"]'),
            "note": ('["', '"]'),
            "db": ('[("', '")]'),
            "channel": ('{{"', '"}}'),
            "decision": ('{"', '"}'),
        }
        lines = ["flowchart TB"]
        for group in [*self.groups, None]:
            if group:
                lines.append(f'    subgraph {group}["{mermaid_text(self.groups[group])}"]')
            for identity, (title, detail, kind, owner) in self.nodes.items():
                if owner != group:
                    continue
                label = mermaid_text(title)
                if detail:
                    label += "<br/>" + mermaid_text(detail)
                opening, closing = shapes[kind]
                indent = "        " if group else "    "
                lines.append(f"{indent}{identity}{opening}{label}{closing}")
            if group:
                lines.append("    end")
        for source, target, operator, label in self.edges:
            if source not in self.nodes or target not in self.nodes:
                raise ValueError(f"Unknown diagram edge endpoint: {source} -> {target}")
            annotation = f'|"{mermaid_text(label)}"|' if label else ""
            lines.append(f"    {source} {operator}{annotation} {target}")
        lines.extend([
            f"    classDef default fill:{PAPER},stroke:{INK},color:{INK}",
            f"    classDef db fill:{SURFACE},stroke:{MUTED},color:{INK}",
            f"    classDef channel fill:{INK},stroke:{INK},color:{PAPER}",
            f"    classDef note fill:{PAPER},stroke:{MUTED},color:{MUTED},stroke-dasharray:5 5",
        ])
        for kind in ["db", "channel", "note"]:
            identities = [identity for identity, node in self.nodes.items() if node[2] == kind]
            if identities:
                lines.append(f"    class {','.join(identities)} {kind}")
        save_mermaid(name, lines)


class Canvas:
    def __init__(self, width, height, title, description):
        self.parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title description">',
            f'<title id="title">{escape(title)}</title>',
            f'<desc id="description">{escape(description)}</desc>',
            '<defs>',
        ]
        for name, color in [("ink", INK), ("muted", MUTED), ("accent", ACCENT)]:
            self.parts.append(
                f'<marker id="arrow-{name}" markerWidth="9" markerHeight="9" '
                'refX="8" refY="4.5" orient="auto" markerUnits="userSpaceOnUse">'
                f'<path d="M1 1 L8 4.5 L1 8" fill="none" stroke="{color}" '
                'stroke-width="1.5"/></marker>'
            )
        self.parts.extend([
            '</defs>',
            f'<g font-family="{SANS}">',
            f'<rect width="{width}" height="{height}" fill="{PAPER}"/>',
        ])

    def rect(self, x, y, w, h, fill=PAPER, stroke="none", dash=False):
        dash_attr = ' stroke-dasharray="5 5"' if dash else ""
        self.parts.append(
            f'<rect x="{x}" y="{y}" width="{w}" height="{h}" '
            f'fill="{fill}" stroke="{stroke}" stroke-width="1.2"{dash_attr}/>'
        )

    def text(self, x, y, lines, size=17, color=INK, weight=400, anchor="start", gap=None, mono=False):
        if isinstance(lines, str):
            lines = [lines]
        gap = gap or size * 1.45
        font = f' font-family="{MONO}"' if mono else ""
        self.parts.append(
            f'<text x="{x}" y="{y}" fill="{color}" font-size="{size}" '
            f'font-weight="{weight}" text-anchor="{anchor}"{font}>'
        )
        for i, line in enumerate(lines):
            self.parts.append(f'<tspan x="{x}" dy="{0 if i == 0 else gap}">{escape(line)}</tspan>')
        self.parts.append('</text>')

    def path(self, d, color=INK, width=1.6, arrow="ink", dash=False):
        marker = f' marker-end="url(#arrow-{arrow})"' if arrow else ""
        dash_attr = ' stroke-dasharray="6 5"' if dash else ""
        self.parts.append(
            f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{width}" '
            f'stroke-linejoin="miter"{marker}{dash_attr}/>'
        )

    def rule(self, x1, y, x2, color=RULE, width=1):
        self.path(f"M{x1} {y} H{x2}", color, width, arrow=None)

    def card(self, x, y, w, h, title, detail=None):
        self.rect(x, y, w, h, PAPER, INK)
        self.text(x + 16, y + 32, title, 19, weight=600)
        if detail:
            self.text(x + 16, y + 57, detail, 13, MUTED)

    def database(self, x, y, w, h, title, detail=None):
        self.parts.append(
            f'<path d="M{x} {y + 12} V{y + h - 12} '
            f'A{w / 2} 12 0 0 0 {x + w} {y + h - 12} V{y + 12}" '
            f'fill="{SURFACE}" stroke="{MUTED}" stroke-width="1.2"/>'
            f'<ellipse cx="{x + w / 2}" cy="{y + 12}" rx="{w / 2}" ry="12" '
            f'fill="{PAPER}" stroke="{MUTED}" stroke-width="1.2"/>'
        )
        self.text(x + w / 2, y + 40, title, 15, weight=600, anchor="middle", mono=True)
        if detail:
            self.text(x + w / 2, y + 60, detail, 12, MUTED, anchor="middle")

    def channel(self, x, y, w, h, title, detail, dark=False):
        self.parts.append(
            f'<path d="M{x + 20} {y} H{x + w - 20} L{x + w} {y + h / 2} '
            f'L{x + w - 20} {y + h} H{x + 20} L{x} {y + h / 2} Z" '
            f'fill="{INK if dark else PAPER}" stroke="{INK}" stroke-width="1.5"/>'
        )
        self.text(x + w / 2, y + 30, title, 20, PAPER if dark else INK, 600, "middle")
        self.text(x + w / 2, y + 54, detail, 12, "#d4d4d0" if dark else MUTED, anchor="middle", mono=True)

    def header(self, category, title, subtitle):
        self.rect(40, 30, 8, 8, ACCENT)
        self.text(60, 39, category, 12, MUTED, mono=True)
        self.text(40, 94, title, 44, weight=600)
        self.text(40, 128, subtitle, 16, MUTED)

    def save(self, name):
        self.parts.extend(['</g>', '</svg>'])
        (ROOT / name).write_text("\n".join(self.parts) + "\n", encoding="utf-8")


